def run_regime_study(
    raw_dir: Path = Path("data/raw"),
    output_root: Path = DEFAULT_OUTPUT_ROOT,
    symbol: str = "BTCUSDT",
    timeframe: str = "1h",
) -> Path:
    baseline_fingerprint = _require_phase3_intact()

    output_root.mkdir(parents=True, exist_ok=True)

    df = load_ohlcv(symbol, timeframe, raw_dir=raw_dir)
    df = df.copy()
    df["timestamp"] = pd.to_datetime(df["timestamp"], utc=True)
    df = df.sort_values("timestamp").reset_index(drop=True)

    features = compute_regime_features(df)

    split = split_final_holdout(df, RECENT_START)
    recent_ts = pd.to_datetime(split.final_holdout["timestamp"], utc=True)
    recent_df = split.final_holdout.loc[recent_ts <= pd.Timestamp(RECENT_END, tz="UTC")]

    research_features = features[features["timestamp"] < pd.Timestamp(RECENT_START, tz="UTC")]
    recent_features = features[
        (features["timestamp"] >= pd.Timestamp(RECENT_START, tz="UTC"))
        & (features["timestamp"] <= pd.Timestamp(RECENT_END, tz="UTC"))
    ]

    feature_distributions = build_feature_distributions(research_features, recent_features)
    feature_distributions.to_csv(output_root / "feature_distributions.csv", index=False)

    entry_features = build_entry_feature_table(features)
    entry_features.to_csv(output_root / "entry_feature_analysis.csv", index=False)

    winner_loser = build_winner_loser_separation(entry_features)
    winner_loser.to_csv(output_root / "winner_loser_separation.csv", index=False)

    yearly = build_yearly_analysis(entry_features)
    yearly.to_csv(output_root / "yearly_analysis.csv", index=False)

    sim_config = BacktestConfig(initial_capital=10_000.0, trading_fee=0.001, slippage=0.0002)
    simulations_dir = output_root / "posthoc_simulations"
    simulation_reports = []
    for spec in EXPLORATORY_SIMULATIONS:
        report = run_exploratory_gate_simulation(
            spec["hypothesis_id"],
            spec["strategy_factory"],
            df,
            spec["gate_fn"],
            features[spec["feature_column"]],
            sim_config,
            timeframe,
            simulations_dir / spec["output_subdir"],
        )
        simulation_reports.append(report)

    final_fingerprint = _require_phase3_intact()
    if final_fingerprint != baseline_fingerprint:
        raise Phase3IntegrityError(
            "Phase 3 forward preregistration changed DURING this regime study run "
            "(fingerprint differs between start and end). This should be impossible "
            "since this module never writes to Phase 3's files -- investigate "
            "immediately."
        )
    with open(output_root / "PHASE3_FINGERPRINT.json", "w") as f:
        json.dump(
            {"before": baseline_fingerprint, "after": final_fingerprint},
            f,
            indent=2,
            default=str,
        )

    metadata = {
        "status": LABEL_FULL,
        "purpose": (
            "Investigates whether causal trailing-only regime features can "
            "explain when NOT to trade a trend/breakout strategy. No new "
            "strategy parameters searched. No thresholds grid-searched. No "
            "machine learning used. Produces at most 3 candidate forward "
            "hypotheses for future preregistration; does not implement or "
            "run any new forward test."
        ),
        "symbol": symbol,
        "timeframe": timeframe,
        "research_period": {
            "start": str(research_features["timestamp"].min()),
            "end": str(research_features["timestamp"].max()),
        },
        "recent_period": {"start": RECENT_START, "end": RECENT_END, "note": "POST-HOC, already consumed"},
        "dataset_hash_full": dataset_hash(df),
        "feature_columns": FEATURE_COLUMNS,
        "trade_sources": {k: {p: str(v[p]) for p in v} for k, v in TRADE_SOURCES.items()},
        "phase3_fingerprint_at_start": baseline_fingerprint,
        "phase3_fingerprint_at_end": final_fingerprint,
        "phase3_intact": True,
        "forbidden": [
            "out-of-sample", "validated", "proven",
            "grid search", "threshold search", "machine learning",
        ],
        "max_hypotheses_allowed": MAX_HYPOTHESES,
        "exploratory_simulations_run": [r["hypothesis_id"] for r in simulation_reports],
        "exploratory_simulations_summary": [
            {
                "hypothesis_id": r["hypothesis_id"],
                "baseline_total_return": r["baseline_metrics"].get("total_return"),
                "gated_total_return": r["gated_metrics"].get("total_return"),
                "gate_impact": r["gate_impact"],
            }
            for r in simulation_reports
        ],
    }
    with open(output_root / "metadata.json", "w") as f:
        json.dump(metadata, f, indent=2, default=str)

    return output_root
