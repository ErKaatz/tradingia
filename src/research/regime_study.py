def _psi(research: pd.Series, recent: pd.Series, n_bins: int = 10) -> float | None:
    """Population Stability Index between two distributions of the same
    feature, using research-period decile edges (a standard, simple PSI
    construction: bin edges are fixed from the reference/research
    distribution, then both distributions are binned into those same
    edges). Returns None if either series has too few valid values to form
    bins.
    """
    research = research.dropna()
    recent = recent.dropna()
    if len(research) < n_bins * 5 or len(recent) < n_bins * 5:
        return None

    quantiles = np.linspace(0, 1, n_bins + 1)
    edges = np.unique(research.quantile(quantiles).to_numpy())
    if len(edges) < 3:
        return None  # degenerate distribution, can't form meaningful bins

    research_counts, _ = np.histogram(research, bins=edges)
    recent_counts, _ = np.histogram(recent, bins=edges)

    research_frac = research_counts / research_counts.sum()
    recent_frac = recent_counts / recent_counts.sum()

    # Avoid log(0) / division by zero for empty bins with a small epsilon,
    # a standard PSI convention.
    eps = 1e-6
    research_frac = np.clip(research_frac, eps, None)
    recent_frac = np.clip(recent_frac, eps, None)

    return float(np.sum((recent_frac - research_frac) * np.log(recent_frac / research_frac)))


def build_feature_distributions(
    research_features: pd.DataFrame, recent_features: pd.DataFrame
) -> pd.DataFrame:
    """Compare each feature's distribution between the research and recent
    periods: mean, median, p10/p25/p75/p90, std, standardized mean
    difference, KS statistic, and PSI. No threshold is selected here --
    this is purely descriptive (Task 2).
    """
    rows = []
    for col in FEATURE_COLUMNS:
        research_vals = research_features[col].dropna()
        recent_vals = recent_features[col].dropna()
        if len(research_vals) < 30 or len(recent_vals) < 30:
            rows.append(
                {
                    "feature": col,
                    "n_research": len(research_vals),
                    "n_recent": len(recent_vals),
                    "note": "insufficient non-null observations in one or both periods",
                }
            )
            continue

        pooled_std = np.sqrt(
            ((len(research_vals) - 1) * research_vals.std(ddof=1) ** 2
             + (len(recent_vals) - 1) * recent_vals.std(ddof=1) ** 2)
            / (len(research_vals) + len(recent_vals) - 2)
        )
        standardized_diff = (
            (recent_vals.mean() - research_vals.mean()) / pooled_std if pooled_std > 0 else None
        )
        ks_stat, ks_pvalue = ks_2samp(research_vals, recent_vals)

        rows.append(
            {
                "feature": col,
                "n_research": len(research_vals),
                "n_recent": len(recent_vals),
                "research_mean": research_vals.mean(),
                "recent_mean": recent_vals.mean(),
                "research_median": research_vals.median(),
                "recent_median": recent_vals.median(),
                "research_p10": research_vals.quantile(0.10),
                "recent_p10": recent_vals.quantile(0.10),
                "research_p25": research_vals.quantile(0.25),
                "recent_p25": recent_vals.quantile(0.25),
                "research_p75": research_vals.quantile(0.75),
                "recent_p75": recent_vals.quantile(0.75),
                "research_p90": research_vals.quantile(0.90),
                "recent_p90": recent_vals.quantile(0.90),
                "research_std": research_vals.std(ddof=1),
                "recent_std": recent_vals.std(ddof=1),
                "standardized_mean_diff": standardized_diff,
                "ks_statistic": float(ks_stat),
                "ks_pvalue": float(ks_pvalue),
                "psi": _psi(research_vals, recent_vals),
                "note": "",
            }
        )
    return pd.DataFrame(rows)


