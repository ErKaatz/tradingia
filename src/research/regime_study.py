def _load_trades(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Expected already-generated trade artifact not found: {path}. "
            "This module reads existing research/recent trade logs; it does "
            "not re-run any backtest."
        )
    df = pd.read_csv(path)
    df["entry_time"] = pd.to_datetime(df["entry_time"], utc=True)
    return df


def build_entry_feature_table(features: pd.DataFrame) -> pd.DataFrame:
    """For each configured trade source, attach regime-feature values as of
    each trade's entry_time (backward as-of lookup, never forward -- see
    feature_values_at), tagging period (research/recent) and outcome
    (winner/loser by net_pnl sign).
    """
    rows = []
    for strategy_name, paths in TRADE_SOURCES.items():
        for period in ("research", "recent"):
            trades = _load_trades(paths[period])
            if trades.empty:
                continue
            entry_features = feature_values_at(features, trades["entry_time"])
            for i in range(len(trades)):
                trade = trades.iloc[i]
                feat_row = entry_features.iloc[i]
                row = {
                    "strategy": strategy_name,
                    "period": period,
                    "entry_time": trade["entry_time"],
                    "net_pnl": trade["net_pnl"],
                    "return_pct": trade["return_pct"],
                    "outcome": "winner" if trade["net_pnl"] > 0 else "loser",
                }
                for col in FEATURE_COLUMNS:
                    row[col] = feat_row[col]
                rows.append(row)
    return pd.DataFrame(rows)


def _cohens_d(a: pd.Series, b: pd.Series) -> float | None:
    a, b = a.dropna(), b.dropna()
    if len(a) < 2 or len(b) < 2:
        return None
    pooled_std = np.sqrt(
        ((len(a) - 1) * a.std(ddof=1) ** 2 + (len(b) - 1) * b.std(ddof=1) ** 2)
        / (len(a) + len(b) - 2)
    )
    if pooled_std == 0:
        return None
    return float((a.mean() - b.mean()) / pooled_std)


def _univariate_auc(a: pd.Series, b: pd.Series) -> float | None:
    """AUC of using the feature alone to separate group `a` (treated as the
    positive class) from group `b`, computed directly from the
    Mann-Whitney U statistic (AUC = U / (n_a * n_b)) -- avoids adding a
    dependency on scikit-learn for a single, simple statistic.
    """
    a, b = a.dropna(), b.dropna()
    if len(a) < 2 or len(b) < 2:
        return None
    u_stat, _ = mannwhitneyu(a, b, alternative="two-sided")
    return float(u_stat / (len(a) * len(b)))


def build_winner_loser_separation(entry_features: pd.DataFrame) -> pd.DataFrame:
    """Univariate separation between winners and losers, per feature, per
    strategy, per period (Task 4). Exploratory only: reports effect sizes
    and sample counts, never selects a feature as "predictive" from a
    p-value alone, and never proposes a cutoff.
    """
    rows = []
    for (strategy, period), group in entry_features.groupby(["strategy", "period"]):
        winners = group[group["outcome"] == "winner"]
        losers = group[group["outcome"] == "loser"]
        for col in FEATURE_COLUMNS:
            w = winners[col].dropna()
            l = losers[col].dropna()
            row: dict[str, Any] = {
                "strategy": strategy,
                "period": period,
                "feature": col,
                "n_winners": len(w),
                "n_losers": len(l),
            }
            if len(w) < 5 or len(l) < 5:
                row["note"] = "fewer than 5 observations in a group; not reported"
                rows.append(row)
                continue
            row["winner_median"] = w.median()
            row["loser_median"] = l.median()
            row["median_diff"] = w.median() - l.median()
            row["cohens_d"] = _cohens_d(w, l)
            try:
                u_stat, p_value = mannwhitneyu(w, l, alternative="two-sided")
                row["mannwhitney_u"] = float(u_stat)
                row["mannwhitney_pvalue"] = float(p_value)
            except ValueError:
                row["mannwhitney_u"] = None
                row["mannwhitney_pvalue"] = None
            row["univariate_auc"] = _univariate_auc(w, l)
            row["note"] = ""
            rows.append(row)
    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Task 11: yearly robustness
# ---------------------------------------------------------------------------


def build_yearly_analysis(entry_features: pd.DataFrame) -> pd.DataFrame:
    """Per-year (2018-2026 YTD) trade counts, win rate, and median feature
    values at entry, per strategy. Purely descriptive -- flags whether an
    observed pattern is concentrated in one year or spread across several.
    2025/2026 rows are explicitly still post-hoc, never out-of-sample.
    """
    rows = []
    df = entry_features.copy()
    df["year"] = df["entry_time"].dt.year
    for (strategy, year), group in df.groupby(["strategy", "year"]):
        row = {
            "strategy": strategy,
            "year": int(year),
            "period_label": "research" if year < 2025 else "recent (post-hoc)",
            "n_trades": len(group),
            "win_rate": float((group["outcome"] == "winner").mean()),
            "median_net_pnl": group["net_pnl"].median(),
        }
        for col in FEATURE_COLUMNS:
            row[f"median_{col}"] = group[col].median()
        rows.append(row)
    return pd.DataFrame(rows).sort_values(["strategy", "year"])


